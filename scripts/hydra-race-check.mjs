import { chromium } from '@playwright/test'
import assert from 'node:assert/strict'
import { mkdir } from 'node:fs/promises'
import sharp from 'sharp'

const browser = await chromium.launch({ args: ['--enable-webgl', '--ignore-gpu-blocklist'] })
const page = await browser.newPage({ viewport: { width: 1280, height: 900 }, reducedMotion: 'reduce' })
const errors = []
await page.clock.install()
page.on('pageerror', error => errors.push(error.message))
await mkdir('/tmp/hydra-check', { recursive: true })
try {
  const baseURL = process.env.HYDRA_URL || 'http://127.0.0.1:5175/hydra'
  await page.goto(baseURL)
  await page.waitForTimeout(1800)
  const stage = page.locator('.race-stage')
  await stage.scrollIntoViewIfNeeded()
  await page.getByRole('button', { name: 'Start race', exact: true }).waitFor()
  await page.waitForTimeout(2000)
  await page.screenshot({ path: '/tmp/hydra-check/garage-desktop.png' })
  await page.getByRole('button', { name: 'Ridge R Rally' }).click()
  assert.equal(await page.locator('.race-car-title h3').textContent(), 'Ridge R')
  await page.getByRole('button', { name: 'Start race', exact: true }).click()
  await page.locator('.race-countdown').waitFor({ state: 'hidden', timeout: 60000 })
  await page.keyboard.down('ArrowUp')
  await page.waitForFunction(() => Number(document.querySelector('.race-speed>strong')?.textContent) > 50, null, { timeout: 60000 })
  await page.keyboard.down('ArrowRight')
  await page.waitForTimeout(500)
  await page.keyboard.up('ArrowRight')
  await page.keyboard.down('Shift')
  await page.waitForTimeout(1000)
  await page.keyboard.up('Shift')
  await page.keyboard.up('ArrowUp')
  assert.ok(Number(await page.locator('.race-speed>strong').textContent()) > 30, 'accelerates')
  assert.ok(Number(await page.locator('.race-speed meter').getAttribute('value')) < 100, 'boost consumes charge')
  await page.screenshot({ path: '/tmp/hydra-check/racing-desktop.png' })
  await page.keyboard.press('Escape')
  await page.getByText('Race paused', { exact: true }).waitFor()
  const time = await page.locator('.race-standing time').textContent()
  await page.waitForTimeout(500)
  assert.equal(await page.locator('.race-standing time').textContent(), time)
  await page.getByRole('button', { name: 'Resume', exact: true }).click()
  await page.keyboard.press('r')
  await page.locator('.race-countdown').waitFor()
  const stats = await page.locator('.race-canvas').evaluate(el => ({ ...el.dataset }))
  await page.keyboard.press('Escape')
  await page.getByText('Race paused', { exact: true }).waitFor()
  await page.getByRole('button', { name: 'Garage', exact: true }).click()
  const canvasImage = await page.locator('.race-canvas canvas').screenshot()
  const pixels = await sharp(canvasImage).stats()
  assert.ok(pixels.channels[0].stdev > 15, 'canvas contains varied rendered pixels')
  console.log({ stats, pixelDeviation: pixels.channels[0].stdev, errors })
  // Exercise a complete race quickly without submitting thousands of GPU frames.
  await page.evaluate(() => {
    const gl=document.querySelector('.race-canvas canvas').getContext('webgl2')
    for(const method of ['drawElements','drawArrays','drawElementsInstanced','drawArraysInstanced','clear']) gl[method]=()=>{}
  })
  await page.getByRole('button', { name: 'Start race', exact: true }).click()
  await page.keyboard.down('ArrowUp')
  await page.clock.runFor(240000)
  await page.keyboard.up('ArrowUp')
  assert.equal(await stage.getAttribute('data-phase'), 'finished', 'three laps produce a finish')
  assert.equal(await page.locator('.race-standing p').textContent(), 'LAP 3 / 3')
  console.log('Complete three-lap race and results passed')
  await page.close()
  const mobile = await browser.newPage({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true, reducedMotion: 'reduce' })
  mobile.on('pageerror', error => errors.push(error.message))
  await mobile.goto(baseURL)
  await mobile.waitForTimeout(1800)
  await mobile.locator('.race-stage').scrollIntoViewIfNeeded()
  await mobile.getByRole('button', { name: 'Start race', exact: true }).waitFor()
  await mobile.waitForTimeout(1500)
  await mobile.locator('.race-stage').screenshot({ path: '/tmp/hydra-check/garage-mobile.png' })
  assert.equal(await mobile.evaluate(() => document.documentElement.scrollWidth > innerWidth), false, 'no mobile overflow')
  await mobile.getByRole('button', { name: 'Start race', exact: true }).click()
  await mobile.getByRole('button', { name: 'Accelerate', exact: true }).waitFor({ timeout: 60000 })
  const throttle = mobile.getByRole('button', { name: 'Accelerate', exact: true })
  const bounds = await throttle.boundingBox()
  const cdp = await mobile.context().newCDPSession(mobile)
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x: bounds.x+bounds.width/2, y: bounds.y+bounds.height/2 }] })
  await mobile.waitForFunction(() => Number(document.querySelector('.race-speed>strong')?.textContent) > 20, null, { timeout: 60000 })
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] })
  assert.ok(Number(await mobile.locator('.race-speed>strong').textContent()) > 15, 'touch accelerates')
  await mobile.locator('.race-stage').screenshot({ path: '/tmp/hydra-check/racing-mobile.png' })
  assert.deepEqual(errors, [])
  console.log('Hydra desktop and mobile checks passed')
} finally { await browser.close() }
